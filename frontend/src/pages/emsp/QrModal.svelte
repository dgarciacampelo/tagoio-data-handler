<!--
@component
QR code of a station's public page: a 280×320 card (three times sharper on the canvas) with the station title and
the code, downloadable as PNG, and the printable A5 and A4 posters.
-->
<script lang="ts">
	import { fade, scale } from 'svelte/transition';
	import type { StationLink } from '$lib/contract.gen';
	import Icon from '$lib/components/Icon.svelte';
	import { m } from '$lib/paraglide/messages';

	let { link, onClose }: { link: StationLink; onClose: () => void } = $props();

	const pixelRatio = 3; // Print-quality PNG (840×960)
	const width = 280;
	const height = 320;
	const brandGreen = '#00571b';

	let canvas = $state<HTMLCanvasElement>();
	let ready = $state(false);

	// Draws the card: white background, the title in brand green, and the QR image (generated by the server).
	$effect(() => {
		const target = canvas;
		if (!target) return;
		ready = false;
		const context = target.getContext('2d');
		if (!context) return;

		target.width = width * pixelRatio;
		target.height = height * pixelRatio;
		context.scale(pixelRatio, pixelRatio);
		context.fillStyle = '#ffffff';
		context.fillRect(0, 0, width, height);
		context.fillStyle = brandGreen;
		context.font = 'bold 14px "Segoe UI", Tahoma, sans-serif';
		context.textAlign = 'center';
		context.fillText(m.emsp_qr_canvas_title({ pool: String(link.pool_code), station: link.station_name }), width / 2, 24);

		const image = new Image();
		let cancelled = false;
		image.onload = () => {
			if (cancelled) return;
			context.imageSmoothingEnabled = false; // Keep the modules sharp
			context.drawImage(image, 0, 35, width, width);
			ready = true;
		};
		image.src = link.qr_image_url;
		return () => {
			cancelled = true;
		};
	});

	function downloadPNG() {
		if (!canvas) return;
		const anchor = document.createElement('a');
		anchor.download = `VeloEnergy_QR_${link.pool_code}_${link.station_name}.png`;
		anchor.href = canvas.toDataURL('image/png');
		anchor.click();
	}

	function onKeydown(event: KeyboardEvent) {
		if (event.key === 'Escape') onClose();
	}
</script>

<svelte:window onkeydown={onKeydown} />

<!-- svelte-ignore a11y_click_events_have_key_events, a11y_no_static_element_interactions (Escape closes it too) -->
<div
	class="fixed inset-0 z-50 bg-black/60 flex items-center justify-center p-4"
	transition:fade={{ duration: 300 }}
	onclick={(event) => event.target === event.currentTarget && onClose()}
>
	<div
		class="bg-surface rounded-2xl shadow-xl w-[calc(100vw-32px)] sm:w-[28rem] overflow-hidden"
		role="dialog"
		aria-modal="true"
		aria-labelledby="qr-modal-title"
		transition:scale={{ duration: 300, start: 0.95 }}
	>
		<div class="flex justify-between items-start p-4 border-b border-outline-variant">
			<div class="flex flex-col">
				<span class="font-label-sm text-on-surface-variant uppercase tracking-wider">{link.cpo_name || '—'}</span>
				<h3 class="font-headline-md text-on-surface" id="qr-modal-title">{link.pool_code} / {link.station_name}</h3>
			</div>
			<button type="button" onclick={onClose} class="text-on-surface-variant hover:text-error transition-colors mt-1" aria-label={m.common_close()}>
				<Icon name="close" />
			</button>
		</div>

		<div class="p-6 flex flex-col items-center gap-4">
			<div class="bg-white p-4 rounded-xl border border-outline-variant shadow-sm min-w-[300px] min-h-[350px] flex items-center justify-center">
				<canvas bind:this={canvas} style="width: {width}px; height: {height}px;" aria-label={m.poster_qr_alt()}></canvas>
			</div>

			<p class="text-center font-label-sm text-on-surface-variant break-all">{link.url}</p>

			<div class="flex flex-col sm:flex-row gap-3 w-full mt-4">
				<button
					type="button"
					onclick={downloadPNG}
					disabled={!ready}
					class="flex-1 bg-surface-container-high hover:bg-surface-container-highest text-on-surface font-label-sm py-2 px-4 rounded-lg flex items-center justify-center gap-2 border border-outline-variant disabled:opacity-50"
				>
					<Icon name="download" size={18} />
					{m.emsp_qr_png()}
				</button>
				<a
					href={link.poster_a5_url}
					target="_blank"
					rel="noopener"
					class="flex-1 bg-primary hover:bg-on-primary-fixed-variant text-on-primary font-label-sm py-2 px-4 rounded-lg flex items-center justify-center gap-2"
				>
					<Icon name="print" size={18} />
					{m.emsp_qr_poster_a5()}
				</a>
				<a
					href={link.poster_a4_url}
					target="_blank"
					rel="noopener"
					class="flex-1 border border-outline hover:bg-surface-container-low text-primary font-label-sm py-2 px-4 rounded-lg flex items-center justify-center gap-2"
				>
					<Icon name="print" size={18} />
					{m.emsp_qr_poster_a4()}
				</a>
			</div>
		</div>
	</div>
</div>
